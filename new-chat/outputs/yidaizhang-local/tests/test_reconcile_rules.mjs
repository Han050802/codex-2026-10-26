import assert from 'node:assert/strict';
import {bindRuleSearch, renderRuleSearch, ruleResultsMarkup} from '../public/reconcile-rules.js';

assert.match(renderRuleSearch(), /发票科目规则查询/);
const unsafe = {role:'purchase',account_name:'<img src=x onerror=alert(1)>',conditions:'<script>bad()</script>',explanation:'a & b',source_title:'<来源>',source_url:'javascript:alert(1)'};
const escaped = ruleResultsMarkup({rules:[unsafe]});
assert.doesNotMatch(escaped, /<script>|<img |href=/);
assert.match(escaped, /&lt;img/);
assert.match(escaped, /a &amp; b/);
assert.match(ruleResultsMarkup({rules:[{...unsafe,source_url:'https://example.org/standard?a=1&b=2'}]}), /href="https:\/\/example.org\/standard\?a=1&amp;b=2"/);
assert.throws(()=>ruleResultsMarkup({rules:null}), /格式/);

let submit;
const form = {addEventListener(type,fn){assert.equal(type,'submit'); submit=fn;}};
const input = {value:'办公用品'};
const result = {textContent:'',innerHTML:''};
const section = {querySelector(selector){return {'[data-rc-rule-form]':form,'[data-rc-rule-query]':input,'[data-rc-rule-result]':result}[selector];}};
const root = {querySelector(){return section;},contains(value){return value===section;}};
let calls=[];
let replies=[];
const api = url => {calls.push(url); return new Promise((resolve,reject)=>replies.push({resolve,reject}));};
bindRuleSearch(root,api,()=>42);
const trigger = () => submit({preventDefault(){}});
let pending=trigger();
assert.match(calls[0], /q=%E5%8A%9E/);
assert.match(calls[0], /client_id=42/);
replies[0].resolve({rules:[{role:'purchase',account_code:'5602',account_name:'管理费用',conditions:'管理用途',explanation:'办公',source_title:'财政部',source_url:'https://example.org'}]});
await pending;
assert.match(result.innerHTML,/5602 管理费用/);
assert.match(result.innerHTML,/管理用途/);
assert.match(result.innerHTML,/财政部/);
pending=trigger(); replies[1].resolve({rules:[]}); await pending;
assert.match(result.innerHTML,/没有找到/);
pending=trigger(); replies[2].reject(new Error('<img src=x>')); await pending;
assert.equal(result.textContent,'规则查询失败：<img src=x>');
const old=trigger(); input.value='广告'; const latest=trigger();
replies[4].resolve({rules:[{account_name:'新结果'}]}); await latest;
replies[3].resolve({rules:[{account_name:'过期结果'}]}); await old;
assert.match(result.innerHTML,/新结果/); assert.doesNotMatch(result.innerHTML,/过期结果/);
console.log('Rule lookup success, empty, error, safety, and out-of-order checks passed');
