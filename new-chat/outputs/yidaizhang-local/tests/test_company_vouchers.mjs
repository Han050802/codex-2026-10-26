import assert from 'node:assert/strict';
import {companyVouchersTest as ui,renderCompanyVouchers} from '../public/company-vouchers.js';

const book={client:{id:771,name:'测试<公司>'},period:'2026-09',periods:[],accounts:[{code:'1001',name:'库存现金'},{code:'2202',name:'应付账款'},{code:'220201',name:'供应商'}],vouchers:[{id:15,date:'2026-09-15',number:1,source_type:'manual',summary:'成本支出',created_by_name:'张会计',status:'active',reviewed:false,attachment_count:2,lines:[{account_code:'1001',account_name:'库存现金',debit_fen:78460,credit_fen:0,summary:'手动摘要'},{account_code:'220201',account_name:'供应商',debit_fen:0,credit_fen:78460}]},{id:16,date:'2026-09-16',number:2,status:'void',summary:'保留记录',lines:[]}]};
const header='分组编号,日期,摘要,科目编码,借方金额,贷方金额,分录摘要,附件数,资金活动';
const text=header+'\r\nA,2026-09-15,"采购,费用",1001,784.60,,现金支出,2,operating\r\nA,2026-09-15,"采购,费用",220201,,784.60,采购款,2,\r\n';
const groups=ui.importGroups(text,book);
assert.equal(groups.length,1);
assert.equal(groups[0].lines[0].debit_fen,78460);
assert.equal(groups[0].lines[1].summary,'采购款');
assert.equal(groups[0].attachment_count,2);
assert.equal(book.vouchers.length,2,'Import validation must never mutate accounting records.');
assert.throws(()=>ui.importGroups(text.replace(',,784.60',',,780.60'),book),/借贷合计/);
assert.throws(()=>ui.importGroups(text.replace(',220201,',',2202,'),book),/不是明细科目/);
assert.throws(()=>ui.importGroups(text.replaceAll('2026-09-15','2026-10-15'),book),/本期/);
assert.throws(()=>ui.importGroups(text.replaceAll('2026-09-15','2026-09-31'),book),/有效日期/);
assert.throws(()=>ui.importGroups(text.replace('现金支出,2,','现金支出,10000,'),book),/附件数/);
assert.throws(()=>ui.parseAmount('1.001'),/两位/);
assert.throws(()=>ui.parseAmount('-1'),/非负/);
assert.throws(()=>ui.parseAmount('999999999999999999999'),/范围/);
assert.equal(ui.parseAmount('0.01'),1);
assert.deepEqual(ui.parseCsv('\uFEFF"摘要","含\n换行"\r\n"a""b",2'),[['摘要','含\n换行'],['a"b','2']]);
assert.throws(()=>ui.parseCsv('"not closed'),/未闭合/);
assert.equal(ui.voucherNumber({number:1}),'记-001');

const state=ui.stateFor(book);
assert.equal(ui.getRows(book,state).length,1,'Default list excludes void history.');
state.query='784.60';assert.equal(ui.getRows(book,state).length,1,'Search understands displayed yuan.');
state.query='供应商';assert.equal(ui.getRows(book,state).length,1,'Search inspects line account names.');
state.query='missing';assert.equal(ui.getRows(book,state).length,0);
state.query='';state.status='void';assert.equal(ui.getRows(book,state)[0].id,16);
state.status='active';state.min='785';assert.equal(ui.getRows(book,state).length,0);state.min='';
assert.notEqual(ui.stateFor({...book,client:{id:772}}),state,'Selection/filter state must be isolated by company.');
assert.notEqual(ui.stateFor({...book,period:'2026-10'}),state,'Selection/filter state must be isolated by period.');

const html=renderCompanyVouchers(book,{});
assert.match(html,/手动摘要/);
assert.match(html,/张会计/);
assert.match(html,/附单据 <u>2 张/);
assert.match(html,/data-book-action="new-voucher"/);
assert.match(html,/data-book-action="edit-voucher"/);
assert.match(html,/data-cv-do="bulk-void"/);
assert.match(html,/data-cv-size/);
assert.doesNotMatch(html,/测试<公司>/);
const hostile={...book,vouchers:[{...book.vouchers[0],summary:'<img src=x onerror=alert(1)>',lines:[{account_code:'1001',account_name:'<b>x</b>',debit_fen:10,credit_fen:0}]}]};
const hostileHtml=renderCompanyVouchers(hostile,{});
assert.doesNotMatch(hostileHtml,/<img src=x/);
assert.match(hostileHtml,/&lt;img/);
const exportRows=ui.exportRows(book.vouchers);
assert.equal(exportRows[1][5],'784.60');
assert.equal(exportRows[1][7],'手动摘要');
assert.equal(exportRows[1][9],'张会计');
const roundtrip=ui.importGroups(exportRows.map(row=>row.map(value=>'"'+String(value).replaceAll('"','""')+'"').join(',')).join('\r\n'),book);
assert.equal(roundtrip.length,1,'CSV exports can be imported using their voucher number as a grouping key.');
assert.equal(roundtrip[0].lines[0].debit_fen,78460);
console.log('company voucher import, money, search, isolation, rendering and export checks passed');
